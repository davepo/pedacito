def file_hash(path: Path) -> str:
    """Short content hash of a file's raw bytes, used to detect edits made
    outside Pedacito between runs."""
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()[:16]
    except OSError:
        return ""


def file_stat(path: Path) -> "list[int] | None":
    """[mtime_ns, size] of a file, or None when it cannot be stat-ed.

    The cheap freshness prefilter for `Index.stale()`: hashing every indexed
    file on every command start (and after every `run` step) reads the whole
    project from disk each time, which is pure waste for the overwhelmingly
    common "nothing changed" answer. A stat sweep gets the same answer for
    unchanged files without opening them; only a stat mismatch pays for a
    hash. A file whose content changes while mtime_ns AND size both stay
    identical is not observable on any filesystem Pedacito targets."""
    try:
        st = path.stat()
        return [st.st_mtime_ns, st.st_size]
    except OSError:
        return None


def state_dir(root: Path, *parts: str) -> Path:
    """Path under <root>/.pedacito/, optionally with subpath components
    appended. Everything Pedacito writes for a project lives here."""
    d = Path(root) / INDEX_DIR
    for p in parts:
        d = d / p
    return d


def infer_root(paths: list[str]) -> Path:
    """Determine the project root when --root wasn't given explicitly: the
    common ancestor of the given paths.

    Without this, running `pedacito ask ~/code/anki` from the Pedacito source
    directory would put .pedacito/ next to Pedacito's own source and render
    every file path relative to the wrong place.
    """
    resolved = []
    for p in paths:
        q = Path(p).resolve()
        resolved.append(q if q.is_dir() else q.parent)
    if not resolved:
        return Path.cwd().resolve()
    if len(resolved) == 1:
        return resolved[0]
    try:
        return Path(os.path.commonpath([str(r) for r in resolved]))
    except ValueError:
        # Different Windows drives have no common path. Fall back to the first.
        return resolved[0]


