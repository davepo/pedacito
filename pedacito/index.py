"""Index construction, persistence, and tiered rendering.

Usage
-----
    from .index import build, Index, reindex_file

    idx = build(["src", "README.md"], cfg, client=llm_client, root=project_root)
    text, tier = idx.map_for_prompt(cfg)     # what goes in every prompt
    idx = reindex_file(idx, "src/app.py", cfg)   # after an edit

An Index has two layers: a static layer from the AST/structural chunkers
(chunker.py, references.py -- exact, free), and a semantic layer of one-line
summaries generated by the LLM (this module -- slow, cached, rationed).

Rendering is tiered, because a flat map does not survive real projects.
Measured on 452KB of stdlib source (inspect/typing/tarfile/argparse, 570
units):

    flat map with summaries   ~35,500 tokens   <- larger than the usable window
    file cards (tier 0)        ~2,000 tokens
    one file's outline (t1)    ~2,400 tokens   <- fetched on demand

The map goes into *every* prompt, so tier 0 is what actually has to be cheap.
The model descends with `outline` (tier 1) and `read` (tier 2) only where it
needs detail. Small projects still get the flat map automatically, since when
it fits it is strictly more useful.

Summarisation is rationed too. Of those 570 units, 442 cleared the length
threshold, but 261 already had a docstring and 281 were methods whose class
summary plus signature says enough. Summarising only undocumented top-level
units cuts it to 76 calls: roughly 4 minutes instead of 24.
"""

